#: Drawn for any character without a glyph: a hollow box.
REPLACEMENT_SOURCE = "##### #...# #...# #...# #...# #...# #####"


def _parse(source: str) -> tuple[int, ...]:
    """Turn a glyph's source string into one row bitmask per line, MSB on the left."""
    rows = source.split()
    if len(rows) != GLYPH_HEIGHT or any(len(row) != GLYPH_WIDTH for row in rows):
        raise ValueError(f"malformed glyph source: {source!r}")
    return tuple(int(row.replace("#", "1").replace(".", "0"), 2) for row in rows)


#: Character to glyph, each glyph being seven row bitmasks with the leftmost
#: pixel in bit 4.
GLYPHS: Mapping[str, tuple[int, ...]] = MappingProxyType(
    {char: _parse(source) for char, source in _SOURCE.items()}
)

#: The glyph drawn for characters the font does not cover.
REPLACEMENT = _parse(REPLACEMENT_SOURCE)


def glyph(char: str) -> tuple[int, ...]:
    """Return the row bitmasks for ``char``, or :data:`REPLACEMENT` if it has none."""
    return GLYPHS.get(char, REPLACEMENT)
